async fn run_demo(config: PublicationConfig, listen: SocketAddr) -> anyhow::Result<()> {
    let (service, store) = build_publication_service(&config).await?;
    let clock: Arc<dyn DemoClock> = Arc::new(SystemDemoClock);
    let state = DemoState {
        service,
        health: store,
        scope: config.default_scope().clone(),
        capacity: Arc::new(tokio::sync::Semaphore::new(16)),
        // ALB and ECS can probe concurrently. Keep readiness isolated from
        // public API capacity while bounding overlapping database checks.
        health_capacity: Arc::new(tokio::sync::Semaphore::new(2)),
        rate_limits: Arc::new(DemoRateLimits::new(clock.now())),
        health_cache: Arc::new(DemoHealthCache::new(DEMO_HEALTH_CACHE_TTL)),
        status_cache: Arc::new(DemoStatusCache::new(DEMO_STATUS_CACHE_TTL)),
        clock,
    };
    let listener = tokio::net::TcpListener::bind(listen)
        .await
        .with_context(|| format!("bind HTTP demo to {listen}"))?;
    tracing::info!(address = %listener.local_addr()?, "fleet recall demo listening");
    axum::serve(listener, demo_router(state))
        .with_graceful_shutdown(shutdown_signal())
        .await
        .context("serve HTTP demo")?;
    Ok(())
}

fn demo_router(state: DemoState) -> Router {
    let api = Router::new()
        .route(
            "/status",
            get(demo_status).route_layer(middleware::from_fn_with_state(
                state.clone(),
                demo_status_rate_limit,
            )),
        )
        .route(
            "/recall",
            post(demo_recall).route_layer(middleware::from_fn_with_state(
                state.clone(),
                demo_recall_rate_limit,
            )),
        )
        .fallback(demo_api_not_found)
        .method_not_allowed_fallback(demo_api_method_not_allowed);
    Router::new()
        .route("/", get(demo_index))
        .route("/healthz", get(demo_health))
        .nest("/api", api)
        .layer(DefaultBodyLimit::max(MAX_DEMO_BODY_BYTES))
        .with_state(state)
}

async fn shutdown_signal() {
    let interrupt = async {
        tokio::signal::ctrl_c()
            .await
            .expect("install Ctrl-C shutdown handler");
    };
    #[cfg(unix)]
    let terminate = async {
        tokio::signal::unix::signal(tokio::signal::unix::SignalKind::terminate())
            .expect("install SIGTERM shutdown handler")
            .recv()
            .await;
    };
    #[cfg(not(unix))]
    let terminate = std::future::pending::<()>();
    tokio::select! {
        () = interrupt => {},
        () = terminate => {},
    }
}

