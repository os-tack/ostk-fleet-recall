#[tokio::main]
async fn main() -> anyhow::Result<ExitCode> {
    tracing_subscriber::fmt()
        .with_env_filter(
            tracing_subscriber::EnvFilter::try_from_default_env()
                .unwrap_or_else(|_| "ostk_fleet_recall=info".into()),
        )
        .with_writer(std::io::stderr)
        .init();

    let cli = Cli::parse();
    match cli.command.runtime_database_identity() {
        RuntimeDatabaseIdentity::None => {
            let Command::ModelDigest { bundle } = cli.command else {
                unreachable!("only model-digest is configuration-free")
            };
            println!("{}", model_bundle_sha256(&bundle)?);
        }
        RuntimeDatabaseIdentity::Publication => {
            let config = PublicationConfig::from_env()?;
            let Command::Demo { listen } = cli.command else {
                unreachable!("only demo uses the publication identity")
            };
            run_demo(config, listen).await?;
        }
        RuntimeDatabaseIdentity::Ingress => {
            let Command::Ingress {
                sources,
                listen,
                allow_non_loopback,
            } = cli.command
            else {
                unreachable!("only ingress uses the ingress identity")
            };
            // Refused before any configuration or secret is read.
            let listen = validate_listen(listen, allow_non_loopback)?;
            let config = IngressConfig::from_env()?;
            run_ingress(&config, &sources, listen).await?;
        }
        RuntimeDatabaseIdentity::Migrator => {
            let config = FleetConfig::from_migrator_env()?;
            let Command::Migrate = cli.command else {
                unreachable!("only migrate uses the schema-migrator identity")
            };
            run_migrate(&config).await?;
        }
        RuntimeDatabaseIdentity::Writer => {
            let config = FleetConfig::from_writer_env()?;
            match cli.command {
                Command::Health => run_health(&config).await?,
                Command::Serve => run_serve(config).await?,
                Command::Ingest { input } => run_ingest(&config, &input).await?,
                Command::Worker {
                    sources,
                    once,
                    steps,
                } => {
                    let command = WorkerCommandV1 {
                        sources,
                        once,
                        steps,
                    };
                    return run_worker(&config, &command).await;
                }
                Command::Collect { command } => {
                    command.validate()?;
                    run_collect(&config, &command.into_command()).await?;
                }
                Command::Demo { .. }
                | Command::Migrate
                | Command::ModelDigest { .. }
                | Command::Ingress { .. } => {
                    unreachable!("command identity was classified before configuration load")
                }
            }
        }
    }
    Ok(ExitCode::SUCCESS)
}

