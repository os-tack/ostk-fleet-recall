    /// The README's shell blocks replayed in order as one session: plain and
    /// exported assignments with `${name}` expansion, `unset`, and whether the
    /// checked-in boundary helper has run. That helper retires
    /// `fleet_migrator`, and only then provisions and enables `fleet_writer`
    /// and `fleet_publication`. Lines continued with `\` are one command,
    /// and the `NAME=value` words that open a command hold for that command
    /// only, as in the shell.
    #[derive(Default)]
    struct QuickstartShell {
        variables: HashMap<String, String>,
        /// The current command's own `NAME=value` prefixes.
        scoped: HashMap<String, String>,
        boundary_established: bool,
    }

    /// `NAME=value` at the start of `words`: the name, the value without its
    /// quotes, and the words after it. `None` when `words` does not start
    /// with an assignment.
    fn split_assignment(words: &str) -> Option<(&str, &str, &str)> {
        let (name, rest) = words.split_once('=')?;
        if name.is_empty() || !name.chars().all(|c| c == '_' || c.is_ascii_alphanumeric()) {
            return None;
        }
        let (value, tail) = match rest.chars().next() {
            Some(quote @ ('"' | '\'')) => {
                let body = &rest[1..];
                let end = body.find(quote).unwrap_or(body.len());
                (&body[..end], body.get(end + 1..).unwrap_or_default())
            }
            _ => rest.split_at(rest.find(char::is_whitespace).unwrap_or(rest.len())),
        };
        Some((name, value, tail.trim_start()))
    }

    impl QuickstartShell {
        /// Replay one command (continued lines joined) and return the words
        /// it runs after its `NAME=value` prefixes, which stay in force for
        /// it until [`Self::finish`].
        fn run(&mut self, line: &str) -> Option<String> {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') {
                return None;
            }
            if line.contains("deploy/localstack/database-boundary.sh") {
                self.boundary_established = true;
            }
            if let Some(names) = line.strip_prefix("unset ") {
                for name in names.split_whitespace() {
                    self.variables.remove(name);
                }
                return None;
            }
            if let Some(assignment) = line.strip_prefix("export ") {
                if let Some((name, value, _)) = split_assignment(assignment) {
                    let value = self.expand(value);
                    self.variables.insert(name.to_owned(), value);
                }
                return None;
            }
            let mut words = line;
            let mut prefixes = Vec::new();
            while let Some((name, value, rest)) = split_assignment(words) {
                prefixes.push((name.to_owned(), self.expand(value)));
                words = rest;
            }
            if words.is_empty() {
                // Plain assignments: shell variables from here on.
                self.variables.extend(prefixes);
                return None;
            }
            self.scoped.extend(prefixes);
            Some(words.to_owned())
        }

        /// End the current command: its prefixes no longer hold.
        fn finish(&mut self) {
            self.scoped.clear();
        }

        fn expand(&self, value: &str) -> String {
            let mut expanded = String::new();
            let mut rest = value;
            while let Some((before, after)) = rest.split_once("${") {
                let (name, tail) = after
                    .split_once('}')
                    .expect("every shell expansion is closed");
                expanded.push_str(before);
                expanded.push_str(self.variables.get(name).map_or("", String::as_str));
                rest = tail;
            }
            expanded.push_str(rest);
            expanded
        }

        /// The login the database URL in `variable` authenticates as.
        fn login(&self, variable: &str) -> Option<String> {
            let url = self
                .scoped
                .get(variable)
                .or_else(|| self.variables.get(variable))?;
            let options = url
                .parse::<sqlx::postgres::PgConnectOptions>()
                .unwrap_or_else(|error| panic!("{variable} is not a PostgreSQL URL: {error}"));
            Some(options.get_username().to_owned())
        }

        /// Whether `login` can authenticate at this point of the session.
        fn login_is_enabled(&self, login: &str) -> bool {
            if login == MIGRATOR_POSTGRES_USER {
                !self.boundary_established
            } else {
                self.boundary_established
            }
        }
    }

    /// Every `"$FLEET_RECALL_BIN"` command the README runs must, at that point
    /// of the walkthrough, have a database URL for the login its identity
    /// requires, and that login must be able to authenticate. A writer
    /// command run with the migrator URL, or before the boundary helper
    /// provisions `fleet_writer`, stops the quickstart.
    #[test]
    fn readme_runs_each_command_as_an_enabled_login_of_its_identity() {
        let mut shell = QuickstartShell::default();
        let mut identities_run = Vec::new();
        let mut fence: Option<&str> = None;
        let mut command = String::new();
        for (index, line) in include_str!("../README.md").lines().enumerate() {
            let line_number = index + 1;
            if let Some(info) = line.strip_prefix("```") {
                fence = if fence.is_some() { None } else { Some(info) };
                continue;
            }
            if fence != Some("bash") {
                continue;
            }
            if let Some(continued) = line.trim_end().strip_suffix('\\') {
                command.push_str(continued);
                command.push(' ');
                continue;
            }
            command.push_str(line);
            let words = shell.run(&std::mem::take(&mut command));
            let Some(arguments) = words
                .as_deref()
                .and_then(|words| words.strip_prefix("\"$FLEET_RECALL_BIN\" "))
            else {
                shell.finish();
                continue;
            };
            let arguments = arguments
                .split_whitespace()
                .take_while(|word| !word.starts_with(['<', '>', '&', '|', ';', ')']));
            let cli = Cli::try_parse_from(std::iter::once("ostk-fleet-recall").chain(arguments))
                .unwrap_or_else(|error| panic!("README line {line_number}: {error}"));
            let identity = cli.command.runtime_database_identity();
            let (variable, login) = match identity {
                RuntimeDatabaseIdentity::None => {
                    shell.finish();
                    continue;
                }
                RuntimeDatabaseIdentity::Migrator => {
                    ("FLEET_RECALL_DATABASE_URL", MIGRATOR_POSTGRES_USER)
                }
                RuntimeDatabaseIdentity::Writer => {
                    ("FLEET_RECALL_DATABASE_URL", WRITER_POSTGRES_USER)
                }
                RuntimeDatabaseIdentity::Publication => {
                    assert_eq!(
                        shell.login("FLEET_RECALL_DATABASE_URL"),
                        None,
                        "README line {line_number}: the public demo refuses a private URL"
                    );
                    (
                        "FLEET_RECALL_PUBLICATION_DATABASE_URL",
                        PUBLICATION_POSTGRES_USER,
                    )
                }
                RuntimeDatabaseIdentity::Ingress => {
                    assert_eq!(
                        shell.login("FLEET_RECALL_DATABASE_URL"),
                        None,
                        "README line {line_number}: the ingress refuses a private URL"
                    );
                    ("FLEET_RECALL_INGRESS_DATABASE_URL", INGRESS_POSTGRES_USER)
                }
            };
            assert_eq!(
                shell.login(variable).as_deref(),
                Some(login),
                "README line {line_number}: a {identity:?} command needs {variable} as {login}"
            );
            assert!(
                shell.login_is_enabled(login),
                "README line {line_number}: {login} cannot authenticate at this step"
            );
            identities_run.push(identity);
            shell.finish();
        }
        for identity in [
            RuntimeDatabaseIdentity::Migrator,
            RuntimeDatabaseIdentity::Writer,
            RuntimeDatabaseIdentity::Publication,
        ] {
            assert!(
                identities_run.contains(&identity),
                "the README never runs a {identity:?} command"
            );
        }
    }

    #[derive(Default)]
    struct DemoService {
        queries: Mutex<Vec<String>>,
        searches: Mutex<Vec<(FleetScope, Map<String, Value>)>>,
        status_calls: AtomicUsize,
        status_failures_remaining: AtomicUsize,
        status_payload: Mutex<Option<Value>>,
        status_block: Mutex<Option<Arc<tokio::sync::Semaphore>>>,
    }

    #[async_trait]
    impl FleetRecallService for DemoService {
        async fn recall(
            &self,
            scope: FleetScope,
            request: RecallRequest,
        ) -> ServiceResult<RecallResult> {
            if request.action == RecallAction::Status {
                self.status_calls.fetch_add(1, Ordering::SeqCst);
                let block = self.status_block.lock().unwrap().clone();
                if let Some(block) = block
                    && block.acquire().await.is_err()
                {
                    return Err(ServiceError::Unavailable(
                        "injected status blocker closed".into(),
                    ));
                }
                if self
                    .status_failures_remaining
                    .fetch_update(Ordering::SeqCst, Ordering::SeqCst, |remaining| {
                        remaining.checked_sub(1)
                    })
                    .is_ok()
                {
                    return Err(ServiceError::Unavailable("injected status failure".into()));
                }
                let value = self
                    .status_payload
                    .lock()
                    .unwrap()
                    .clone()
                    .unwrap_or_else(|| json!({ "status": "ready" }));
                return Ok(RecallResult::new(value));
            }
            let query = request
                .arguments
                .get("query")
                .and_then(Value::as_str)
                .expect("demo query")
                .to_owned();
            if request.arguments.get("kind") == Some(&json!("claim")) {
                assert!(!request.arguments.contains_key("max_per_source_id"));
                assert!(!request.arguments.contains_key("source"));
            } else {
                assert_eq!(request.arguments.get("kind"), Some(&json!("chunk")));
                assert_eq!(request.arguments.get("max_per_source_id"), Some(&json!(1)));
            }
            self.queries.lock().unwrap().push(query);
            self.searches
                .lock()
                .unwrap()
                .push((scope, request.arguments));
            Ok(RecallResult::new(json!({
                "hits": [{
                    "chunk_id": "demo-1",
                    "text": "CockroachDB is the durable shared memory plane.",
                    "score": 0.97
                }]
            })))
        }
    }

