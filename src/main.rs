async fn run_migrate(config: &FleetConfig) -> anyhow::Result<()> {
    let model_identity = validated_migration_model_identity(config)?;
    let store = connect_migrator_store(config).await?;
    store.migrate().await?;
    store.initialize_embedding_model(&model_identity).await?;
    let capabilities = store.capabilities().await?;
    println!("{}", serde_json::to_string_pretty(&capabilities)?);
    Ok(())
}

/// Fully load and probe the model before migration can register its immutable
/// corpus identity. A matching bundle hash alone does not prove that the files
/// form a usable 512-dimension model2vec bundle.
fn validated_migration_model_identity(config: &FleetConfig) -> anyhow::Result<String> {
    let embedder = load_pinned_embedder(config)?;
    let model_identity = config.embedding_model_identity();
    ensure!(
        embedder.model_id() == model_identity,
        "validated migration embedder identity does not match configured registry identity"
    );
    Ok(model_identity)
}

async fn run_health(config: &FleetConfig) -> anyhow::Result<()> {
    config.verify_embedding_model_bundle()?;
    let store = connect_store(config).await?;
    store.health_check().await?;
    let expected_model = config.embedding_model_identity();
    let active_model = active_embedding_model(store.pool(), &config.default_scope)
        .await?
        .ok_or_else(|| {
            anyhow::anyhow!(
                "active embedding generation is not initialized; run ostk-fleet-recall migrate"
            )
        })?;
    ensure!(
        active_model == expected_model,
        "configured embedding model {expected_model:?} does not match active corpus model {active_model:?}"
    );
    let capabilities = store.capabilities().await?;
    println!("{}", serde_json::to_string_pretty(&capabilities)?);
    Ok(())
}

/// `worker --once`: one memory-worker tick as the writer login.
///
/// The library runs the whole command (`worker::run_command`); this binds it
/// to the process: its environment, the pinned model bundle, `gh`, the writer
/// connection, and stdout. The exit status is 1 when any step failed.
async fn run_worker(config: &FleetConfig, command: &WorkerCommandV1) -> anyhow::Result<ExitCode> {
    let load_embedder = || -> ostk_fleet_recall::Result<Arc<dyn ChunkEmbedder>> {
        let embedder = load_pinned_embedder(config)
            .map_err(|error| FleetError::Configuration(format!("{error:#}")))?;
        Ok(Arc::new(embedder))
    };
    let lookup = |name: &str| std::env::var(name).ok();
    let report = ostk_fleet_recall::worker::run_command(
        command,
        WorkerProcessV1 {
            scope: config.default_scope.clone(),
            embedding_model_sha256: &config.embedding_model_sha256,
            load_embedder: &load_embedder,
            lookup: &lookup,
            ci_providers: Arc::new(GhCliProviderFactory),
            retry: RetryPolicy::default(),
        },
        || async {
            let store = connect_store(config).await?;
            let capabilities = store.capabilities().await?;
            Ok((store.pool().clone(), capabilities))
        },
        &mut io::stdout(),
    )
    .await?;
    Ok(ExitCode::from(report.exit_code()))
}

/// `collect`: one import or listing as the writer login.
///
/// The library runs the whole command (`collectors::command`); this binds it
/// to the process: its environment, the writer connection, and stdout.
async fn run_collect(config: &FleetConfig, command: &CollectCommandV1) -> anyhow::Result<()> {
    let lookup = |name: &str| std::env::var(name).ok();
    run_collect_command(
        command,
        CollectProcessV1 {
            scope: config.default_scope.clone(),
            lookup: &lookup,
            retry: RetryPolicy::default(),
        },
        || async {
            let store = connect_store(config).await?;
            let capabilities = store.capabilities().await?;
            Ok((store.pool().clone(), capabilities))
        },
        &mut io::stdout(),
    )
    .await?;
    Ok(())
}

/// `ingress`: the private-plane webhook receiver (ADR 0008 D12), as the
/// `fleet_ingress` login, until interrupted.
///
/// `listen` was already checked ([`validate_listen`]). It reads each
/// webhook's signing secret from the variable the sources file names, and
/// checks, before it listens, that the schema has the hint queue and the
/// login may insert deliveries and dead letters. It holds no content key and
/// no writer pins.
async fn run_ingress(
    config: &IngressConfig,
    sources: &Path,
    listen: SocketAddr,
) -> anyhow::Result<()> {
    let sources = WorkerSourcesV1::load(sources)?;
    let lookup = |name: &str| std::env::var(name).ok();
    let instances = IngressInstancesV1::from_sources(&sources, &lookup)?;
    let pool = CockroachStore::connect_ingress_pool(
        config.database_url(),
        config.database_ssl_policy(),
        PoolConfig {
            max_connections: config.max_connections(),
            ..PoolConfig::default()
        },
    )
    .await?;
    let store = IngressStoreV1::new(pool, config.tenant_id(), config.project())?;
    store.probe().await?;
    let listener = tokio::net::TcpListener::bind(listen)
        .await
        .with_context(|| format!("the ingress cannot listen on {listen}"))?;
    tracing::info!(
        address = %listen,
        instances = ?instances.ids().collect::<Vec<_>>(),
        "the ingress is receiving webhooks"
    );
    let router = ingress_router(store, instances, system_clock(), config.max_body_bytes());
    serve_ingress(listener, router, shutdown_signal()).await?;
    Ok(())
}

async fn run_serve(config: FleetConfig) -> anyhow::Result<()> {
    let (service, _) = build_memory_service(&config).await?;
    McpServer::new(service, config.default_scope)?
        .run_stdio()
        .await?;
    Ok(())
}

async fn build_memory_service(
    config: &FleetConfig,
) -> anyhow::Result<(Arc<CockroachMemoryService>, Arc<CockroachStore>)> {
    let embedder: Arc<dyn ChunkEmbedder> = Arc::new(load_pinned_embedder(config)?);
    let store = Arc::new(connect_store(config).await?);
    store.health_check().await?;
    // One schema snapshot, read once, feeds every startup capability probe.
    let capabilities = store.capabilities().await?;
    // The conflict lifecycle is served only when migration 29 is applied and
    // this role holds its grants; otherwise the claim lifecycle is served
    // alone. The probe runs once, so a later grant change needs a restart.
    let conflict_lifecycle = if config.lifecycle.remember_lifecycle {
        probe_conflict_lifecycle(store.pool(), &capabilities).await?
    } else {
        None
    };
    // recall(kind=item) and claims that cite items (ADR 0008 D7, D11).
    let (items, item_support) = start_items(store.pool(), &capabilities, config).await;
    let mut ledger = CockroachClaimLedger::new(
        store.pool().clone(),
        config.default_scope.clone(),
        embedder.clone(),
        RetryPolicy::default(),
    )?;
    // Adjudication (dismiss and waive) is opt-in per deployment and needs the
    // conflict lifecycle beneath it; a switch that cannot take effect is an
    // operator error worth a loud log, not a startup failure.
    let adjudication = config.lifecycle.conflict_adjudication && conflict_lifecycle.is_some();
    if config.lifecycle.conflict_adjudication && !adjudication {
        tracing::error!(
            "FLEET_RECALL_CONFLICT_ADJUDICATION=enabled is ignored: the conflict lifecycle is not served (FLEET_RECALL_REMEMBER_LIFECYCLE=disabled, or migration 29 or its runtime grants are absent); dismiss and waive stay off"
        );
    }
    if let Some(capability) = conflict_lifecycle {
        ledger = ledger.with_conflict_lifecycle(capability);
        if adjudication {
            ledger = ledger.with_conflict_adjudication();
        }
    }
    if let Some(capability) = item_support {
        ledger = ledger.with_claim_item_links(capability);
    }
    // remember(assert) is served only where the writer-authority pins verify
    // (ADR 0005). Any pin or witness problem turns it off with a logged and
    // reported reason; it never stops serve (D5).
    let (ledger, assert_status) = start_event_first_assert(
        store.pool().clone(),
        &config.default_scope,
        RetryPolicy::default(),
    )
    .await
    .bind_ledger(ledger);
    let assert = assert_status.as_ref().is_some_and(|status| status.served);
    // recall(kind=evidence) is served wherever migration 30 is applied and
    // this login may read the Stage-5 tables (ADR 0006). Like assert, it is
    // additive: a missing grant or a failed probe turns it off with a log
    // line, never stops serve, and leaves every tool schema as it was.
    let evidence = start_evidence_recall(
        store.pool(),
        &capabilities,
        &config.default_scope,
        &config.embedding_model_sha256,
    )
    .await;
    // recall(action=discrepancies) is served wherever migration 31 is applied
    // and this login may read the discrepancy, normative, and spec tables
    // (ADR 0007). It is additive in the same way: a missing grant or a
    // failed probe turns it off with a log line and changes no tool schema.
    let spec_conformance =
        start_spec_conformance(store.pool(), &capabilities, &config.default_scope).await;
    // remember(capture) is served only where FLEET_RECALL_COLLECTED_CAPTURE
    // turns it on and its startup checks pass (ADR 0008 D10): migration 34,
    // capture's grants, the writer-authority pins, a head that binds
    // connector.collected.capture, and, for `enabled`, the content key. Like
    // assert, a problem turns it off with a logged and reported reason and
    // never stops serve; disabled, every tool schema is what it was. An
    // `enabled` capture projects what it admits in the call, embedding with
    // the same pinned model the worker's embed step uses; a provider that
    // cannot be built leaves the dense rows to the worker, never stops serve.
    let capture_embedding = capture_embedding_provider(embedder.clone(), config);
    let (capture, capture_status) = start_collected_capture(
        store.pool().clone(),
        &capabilities,
        &config.default_scope,
        RetryPolicy::default(),
        capture_embedding,
    )
    .await
    .into_parts();
    let captures = capture.is_some();
    let mut service = CockroachMemoryService::new(
        config.default_scope.clone(),
        store.clone(),
        Arc::new(ledger),
        embedder,
    )?
    .with_assert_status(assert_status)
    .with_capture(capture, capture_status);
    if let Some(evidence) = evidence {
        service = service.with_evidence_recall(evidence);
    }
    if let Some(reader) = spec_conformance {
        service = service.with_spec_conformance(reader);
    }
    if let Some(items) = items {
        service = service.with_item_recall(items);
    }
    let serving = with_item_support(
        remember_serving(
            config.lifecycle,
            conflict_lifecycle.is_some(),
            assert,
            captures,
        ),
        item_support.is_some(),
    );
    log_remember_serving(
        serving.as_ref(),
        config.lifecycle,
        conflict_lifecycle.is_some(),
    );
    if let Some(lifecycle) = serving {
        service = service.with_lifecycle(lifecycle);
    }
    let service = Arc::new(service);
    service.verify_embedding_generation().await?;
    Ok((service, store))
}

/// Log the `remember` surface the private writer serves.
fn log_remember_serving(
    serving: Option<&LifecycleServing>,
    lifecycle: LifecycleConfig,
    conflict_lifecycle: bool,
) {
    match serving {
        Some(serving) if lifecycle.remember_lifecycle => {
            tracing::info!(surface = ?serving.surface, "serving the remember lifecycle surface");
            if !conflict_lifecycle {
                tracing::info!(
                    "conflict lifecycle not served: migration 29 or its runtime grants are absent"
                );
            }
        }
        Some(serving) => tracing::info!(surface = ?serving.surface, "serving the remember surface"),
        None => tracing::info!("serving the record-only remember surface"),
    }
}

/// The dense tier's provider for an `enabled` capture: the process's pinned
/// embedder under its configured model digest, as the worker's embed step
/// builds it. `None`, with a logged reason, when the digest or the embedder
/// cannot name the dense tier's model; capture then leaves its dense rows to
/// the worker and reports its projection incomplete.
fn capture_embedding_provider(
    embedder: Arc<dyn ChunkEmbedder>,
    config: &FleetConfig,
) -> Option<Arc<dyn EmbeddingProvider>> {
    let provider = Sha256Digest::from_str(&config.embedding_model_sha256)
        .map_err(|error| error.to_string())
        .and_then(|digest| {
            ChunkEmbedderProvider::new(embedder, digest).map_err(|error| error.to_string())
        });
    match provider {
        Ok(provider) => Some(Arc::new(provider)),
        Err(reason) => {
            tracing::warn!(
                reason,
                "remember(capture) cannot embed what it admits under the pinned model; its dense rows wait for the worker's embed step"
            );
            None
        }
    }
}

/// The `remember` surface the private writer serves, or `None` for the
/// historical record-only surface.
///
/// `conflict_lifecycle` is whether the migration-29 probe passed, `assert`
/// whether the writer-authority pins verified, and `capture` whether agent
/// capture started. The lifecycle switch (`FLEET_RECALL_REMEMBER_LIFECYCLE`)
/// governs every lifecycle action but not `assert`, which is served wherever
/// its pins verify (ADR 0005 D9), nor `capture`, which its own switch governs
/// (ADR 0008 D10); so a disabled switch restores the record-only surface only
/// on a writer that serves neither. Adjudication needs the conflict lifecycle
/// beneath it.
fn remember_serving(
    lifecycle: LifecycleConfig,
    conflict_lifecycle: bool,
    assert: bool,
    capture: bool,
) -> Option<LifecycleServing> {
    if lifecycle.remember_lifecycle {
        Some(LifecycleServing {
            surface: RememberSurface {
                claim_lifecycle: true,
                conflict_lifecycle,
                adjudication: lifecycle.conflict_adjudication && conflict_lifecycle,
                assert,
                capture,
                item_support: false,
            },
            hide_non_current_claim_chunks: true,
            lifecycle_overlay: conflict_lifecycle,
        })
    } else if assert || capture {
        Some(LifecycleServing {
            surface: RememberSurface {
                assert,
                capture,
                ..RememberSurface::RECORD_ONLY
            },
            ..LifecycleServing::default()
        })
    } else {
        None
    }
}

/// `serving`, with claims that cite collected items (ADR 0008 D11) added to
/// its surface when `item_support`: a record-only writer then serves a
/// surface of its own, whose `record` support takes item citations.
fn with_item_support(
    serving: Option<LifecycleServing>,
    item_support: bool,
) -> Option<LifecycleServing> {
    if !item_support {
        return serving;
    }
    let mut serving = serving.unwrap_or_default();
    serving.surface.item_support = true;
    Some(serving)
}

/// `recall(kind=item)`, and whether claims may cite collected items.
///
/// Item recall is served wherever migration 34 is applied and this login may
/// read the collector and Stage-5 tables (ADR 0008 D7). Claims cite items
/// wherever migration 35 is applied, this login holds its grants, and item
/// recall is served, so every cited item can be read back (D11). Both are
/// additive: a missing migration or grant turns them off with a log line and
/// leaves every tool schema as it was.
async fn start_items(
    pool: &sqlx::PgPool,
    capabilities: &DatabaseCapabilities,
    config: &FleetConfig,
) -> (
    Option<Arc<dyn ItemRecall>>,
    Option<ClaimItemLinksCapability>,
) {
    let claim_item_links = start_claim_item_links(pool, capabilities).await;
    let items = start_item_recall_citing(
        pool,
        capabilities,
        &config.default_scope,
        &config.embedding_model_sha256,
        claim_item_links,
    )
    .await;
    let item_support = claim_item_links.filter(|_| items.is_some());
    if claim_item_links.is_some() && item_support.is_none() {
        tracing::info!(
            "claims do not cite collected items: recall(kind=item) is not served, so no cited item could be read back"
        );
    }
    (items, item_support)
}

/// Whether claims may cite collected items: migration 35 is applied and this
/// login may write claim item links and read every table a citation resolves
/// through (ADR 0008 D11). A missing migration or grant is logged at info
/// level, a failed probe at error level; either way it is off and `serve`
/// goes on without it. The probe runs once, so a later grant needs a restart.
async fn start_claim_item_links(
    pool: &sqlx::PgPool,
    capabilities: &DatabaseCapabilities,
) -> Option<ClaimItemLinksCapability> {
    match probe_claim_item_links(pool, capabilities).await {
        Ok(Some(capability)) => Some(capability),
        Ok(None) => {
            tracing::info!(
                "claims do not cite collected items: migration 35 or its runtime grants are absent"
            );
            None
        }
        Err(error) => {
            tracing::error!(
                error = %error,
                "claims do not cite collected items: the claim item links probe failed; serving remember without it"
            );
            None
        }
    }
}

async fn build_publication_service(
    config: &PublicationConfig,
) -> anyhow::Result<(Arc<CockroachMemoryService>, Arc<CockroachStore>)> {
    let embedder: Arc<dyn ChunkEmbedder> = Arc::new(load_pinned_embedder(config)?);
    let store = Arc::new(connect_publication_store(config).await?);
    store.health_check().await?;
    let ledger = Arc::new(CockroachClaimLedger::new(
        store.pool().clone(),
        config.default_scope().clone(),
        embedder.clone(),
        RetryPolicy::default(),
    )?);
    // The public reader withholds every asserted claim (ADR 0005 D8).
    let service = Arc::new(CockroachMemoryService::publication(
        config.default_scope().clone(),
        store.clone(),
        ledger,
        embedder,
    )?);
    service.verify_embedding_generation().await?;
    Ok((service, store))
}

