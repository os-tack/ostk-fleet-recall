#[derive(Debug, Subcommand)]
enum Command {
    /// Serve the Recall MCP protocol over stdin/stdout.
    Serve,
    /// Serve the bounded, read-only demo over HTTP.
    Demo {
        /// Address on which the HTTP demo listens.
        #[arg(long, default_value = "0.0.0.0:8080", value_name = "ADDRESS")]
        listen: SocketAddr,
    },
    /// Apply embedded `CockroachDB` schema migrations.
    Migrate,
    /// Check database connectivity and required capabilities.
    Health,
    /// Upsert trusted, project-scoped chunks from an NDJSON file or stdin.
    Ingest {
        /// NDJSON path, or `-` for stdin.
        #[arg(long, default_value = "-", value_name = "PATH")]
        input: String,
    },
    /// Print the versioned SHA-256 for a local model2vec bundle.
    ModelDigest {
        /// Directory containing config.json, model.safetensors, and tokenizer.json.
        #[arg(value_name = "BUNDLE")]
        bundle: PathBuf,
    },
    /// Run one memory-worker tick: ingest the configured git, transcript, and
    /// CI sources, then project and embed. Prints the tick report as one JSON
    /// line and exits 1 when any step failed.
    Worker {
        /// The worker sources file (JSON).
        #[arg(long, value_name = "PATH")]
        sources: PathBuf,
        /// Run exactly one tick and exit. Required: the worker has no
        /// long-running loop, so schedule it (cron or a scheduled task).
        #[arg(long)]
        once: bool,
        /// Comma-separated step groups: all, ingest, collect, project, embed.
        #[arg(long, default_value = "all", value_name = "GROUPS")]
        steps: String,
    },
    /// Import collected items from a file, or list and retire what the
    /// collectors hold. Prints one JSON document.
    Collect {
        #[command(subcommand)]
        command: CollectSubcommand,
    },
    /// Receive signed provider webhooks on the private plane and keep each
    /// as a hint (ids only) that the worker's collect step re-reads. Runs
    /// until interrupted.
    Ingress {
        /// The worker sources file (JSON): every collector that configures
        /// `push.signing_secret_env` is received.
        #[arg(long, value_name = "PATH")]
        sources: PathBuf,
        /// Address to listen on: loopback unless --allow-non-loopback.
        #[arg(
            long,
            env = "FLEET_RECALL_INGRESS_LISTEN",
            default_value = "127.0.0.1:8787",
            value_name = "ADDRESS"
        )]
        listen: SocketAddr,
        /// Listen on an address that is not loopback, behind a relay you run.
        #[arg(long)]
        allow_non_loopback: bool,
    },
}

#[derive(Debug, Subcommand)]
enum CollectSubcommand {
    /// Import one file of items for one collector instance, as a snapshot of
    /// its provider scope.
    Import {
        /// The import's collector instance.
        #[arg(long, value_name = "INSTANCE")]
        instance: String,
        /// The ingress principal the items are delivered as.
        #[arg(long, value_name = "PRINCIPAL")]
        principal: String,
        /// The provider every line names (docs, slack, linear, granola, ...).
        #[arg(long, value_name = "PROVIDER")]
        provider: String,
        /// The provider scope every line names.
        #[arg(long, value_name = "SCOPE")]
        provider_scope: String,
        /// The operator's declaration that the file is visible to the whole
        /// project.
        #[arg(long, value_enum, value_name = "AUDIENCE")]
        audience: CollectAudienceArg,
        /// The file's format.
        #[arg(long, value_enum, value_name = "FORMAT")]
        format: CollectFormatArg,
        /// The file (for a Slack export, a directory or a zip).
        #[arg(long, value_name = "PATH")]
        path: PathBuf,
        /// A private channel of a Slack export to admit; repeat for each.
        /// The export's other private channels are never read.
        #[arg(long = "private-container", value_name = "CHANNEL")]
        private_containers: Vec<String>,
        /// Stage only, and leave the drain and the snapshot receipt to the
        /// worker's collect step.
        #[arg(long)]
        no_drain: bool,
        /// How long the snapshot stays current (default 30 days).
        #[arg(long, value_name = "SECONDS")]
        stale_after: Option<u64>,
    },
    /// List every collector instance: status row, outbox, cursors, and dead
    /// letters.
    Status,
    /// List dead letters: digests and reasons, never provider text.
    DeadLetters {
        /// Only dead letters recorded at or after this RFC 3339 instant.
        #[arg(long, value_name = "RFC3339")]
        since: Option<String>,
        /// Only this collector instance's.
        #[arg(long, value_name = "INSTANCE")]
        instance: Option<String>,
    },
    /// Retire an import's status row.
    Retire {
        /// The import's collector instance.
        #[arg(long, value_name = "INSTANCE")]
        instance: String,
    },
    /// Reopen an ingress hint the worker gave up on after eight failed
    /// fetches.
    Retry {
        /// The hint's delivery key (the `delivery_id` of its
        /// `retry_exhausted` dead letter), 64 hexadecimal digits.
        #[arg(long, value_name = "HEX")]
        delivery: String,
    },
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, ValueEnum)]
enum CollectAudienceArg {
    /// Everything the file holds is visible to the whole project.
    OperatorDeclared,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, ValueEnum)]
enum CollectFormatArg {
    /// One collected-item input per line.
    ItemsJsonl,
    /// A Slack workspace export: a directory or a zip.
    SlackExport,
}

impl CollectSubcommand {
    /// Refuse flags the chosen format does not read.
    fn validate(&self) -> anyhow::Result<()> {
        if let Self::Import {
            format: CollectFormatArg::ItemsJsonl,
            private_containers,
            ..
        } = self
            && !private_containers.is_empty()
        {
            anyhow::bail!("--private-container applies to --format slack-export only");
        }
        Ok(())
    }

    fn into_command(self) -> CollectCommandV1 {
        match self {
            Self::Import {
                instance,
                principal,
                provider,
                provider_scope,
                audience,
                format,
                path,
                private_containers,
                no_drain,
                stale_after,
            } => CollectCommandV1::Import(CollectImportV1 {
                instance,
                principal,
                provider,
                provider_scope,
                audience: match audience {
                    CollectAudienceArg::OperatorDeclared => ImportAudienceV1::OperatorDeclared,
                },
                format: match format {
                    CollectFormatArg::ItemsJsonl => ImportFormatV1::ItemsJsonl,
                    CollectFormatArg::SlackExport => {
                        ImportFormatV1::SlackExport { private_containers }
                    }
                },
                path,
                no_drain,
                stale_after_seconds: stale_after,
            }),
            Self::Status => CollectCommandV1::Status,
            Self::DeadLetters { since, instance } => {
                CollectCommandV1::DeadLetters { since, instance }
            }
            Self::Retire { instance } => CollectCommandV1::Retire { instance },
            Self::Retry { delivery } => CollectCommandV1::Retry { delivery },
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum RuntimeDatabaseIdentity {
    Writer,
    Migrator,
    Publication,
    Ingress,
    None,
}

impl Command {
    const fn runtime_database_identity(&self) -> RuntimeDatabaseIdentity {
        match self {
            Self::Demo { .. } => RuntimeDatabaseIdentity::Publication,
            Self::Ingress { .. } => RuntimeDatabaseIdentity::Ingress,
            Self::Migrate => RuntimeDatabaseIdentity::Migrator,
            Self::ModelDigest { .. } => RuntimeDatabaseIdentity::None,
            Self::Serve
            | Self::Health
            | Self::Ingest { .. }
            | Self::Worker { .. }
            | Self::Collect { .. } => RuntimeDatabaseIdentity::Writer,
        }
    }
}

