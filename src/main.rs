    #[test]
    fn tsvector_lexeme_limit_counts_utf8_bytes_at_boundary() {
        let ascii_boundary = "a".repeat(MAX_TSVECTOR_INPUT_LEXEME_BYTES);
        assert!(validate_tsvector_lexemes(&ascii_boundary).is_ok());

        let ascii_over = format!("{ascii_boundary}a");
        let error = validate_tsvector_lexemes(&ascii_over)
            .expect_err("one byte over the conservative boundary must fail");
        let message = error.to_string();
        assert!(message.contains("16001 UTF-8 bytes"));
        assert!(message.contains("16383-byte TSVECTOR lexeme limit"));

        let unicode_boundary = "é".repeat(MAX_TSVECTOR_INPUT_LEXEME_BYTES / 2);
        assert_eq!(unicode_boundary.len(), MAX_TSVECTOR_INPUT_LEXEME_BYTES);
        assert!(validate_tsvector_lexemes(&format!("before {unicode_boundary} after")).is_ok());

        let unicode_over = format!("{unicode_boundary}é");
        assert_eq!(unicode_over.len(), MAX_TSVECTOR_INPUT_LEXEME_BYTES + 2);
        let error = validate_tsvector_lexemes(&unicode_over)
            .expect_err("Unicode lexemes must be bounded by bytes, not scalar count");
        assert!(error.to_string().contains("16002 UTF-8 bytes"));
    }

