#[tokio::main]
async fn main() -> anyhow::Result<()> {
    tracing_subscriber::fmt()
        .with_env_filter(
            tracing_subscriber::EnvFilter::try_from_default_env()
                .unwrap_or_else(|_| "ostk_fleet_recall=info".into()),
        )
        .with_writer(std::io::stderr)
        .init();

    let cli = Cli::parse();
    if let Command::ModelDigest { ref bundle } = cli.command {
        println!("{}", model_bundle_sha256(bundle)?);
        return Ok(());
    }

    let config = FleetConfig::from_env()?;
    match cli.command {
        Command::Migrate => run_migrate(&config).await?,
        Command::Health => run_health(&config).await?,
        Command::Serve => run_serve(config).await?,
        Command::Demo { listen } => run_demo(config, listen).await?,
        Command::Ingest { input } => run_ingest(&config, &input).await?,
        Command::ReferenceAgent { step, run_id } => {
            run_reference_agent_step(&config, step, &run_id).await?;
        }
        Command::ModelDigest { .. } => unreachable!("handled without deployment configuration"),
    }
    Ok(())
}

async fn run_reference_agent_step(
    config: &FleetConfig,
    step: ReferenceAgentStep,
    run_id: &str,
) -> anyhow::Result<()> {
    let (service, _) = build_memory_service(config).await?;
    let evidence =
        run_reference_agent(service.as_ref(), config.default_scope.clone(), step, run_id)
            .await
            .map_err(anyhow::Error::msg)?;
    println!("{}", serde_json::to_string(&evidence)?);
    Ok(())
}

async fn connect_store(config: &FleetConfig) -> anyhow::Result<CockroachStore> {
    let pool_config = PoolConfig {
        max_connections: config.max_connections,
        ..PoolConfig::default()
    };
    CockroachStore::connect(
        &config.database_url,
        config.default_scope.clone(),
        pool_config,
    )
    .await
    .map_err(Into::into)
}

async fn run_migrate(config: &FleetConfig) -> anyhow::Result<()> {
    let model_identity = validated_migration_model_identity(config)?;
    let store = connect_store(config).await?;
    store.migrate().await?;
    store.initialize_embedding_model(&model_identity).await?;
    let capabilities = store.capabilities().await?;
    println!("{}", serde_json::to_string_pretty(&capabilities)?);
    Ok(())
}

/// Fully load and probe the model before migration can register its immutable
/// corpus identity. A matching bundle hash alone does not prove that the files
/// form a usable 512-dimension model2vec bundle.
fn validated_migration_model_identity(config: &FleetConfig) -> anyhow::Result<String> {
    let embedder = load_pinned_embedder(config)?;
    let model_identity = config.embedding_model_identity();
    ensure!(
        embedder.model_id() == model_identity,
        "validated migration embedder identity does not match configured registry identity"
    );
    Ok(model_identity)
}

async fn run_health(config: &FleetConfig) -> anyhow::Result<()> {
    config.verify_embedding_model_bundle()?;
    let store = connect_store(config).await?;
    store.health_check().await?;
    let expected_model = config.embedding_model_identity();
    let active_model = active_embedding_model(store.pool(), &config.default_scope)
        .await?
        .ok_or_else(|| {
            anyhow::anyhow!(
                "active embedding generation is not initialized; run ostk-fleet-recall migrate"
            )
        })?;
    ensure!(
        active_model == expected_model,
        "configured embedding model {expected_model:?} does not match active corpus model {active_model:?}"
    );
    let capabilities = store.capabilities().await?;
    println!("{}", serde_json::to_string_pretty(&capabilities)?);
    Ok(())
}

async fn run_serve(config: FleetConfig) -> anyhow::Result<()> {
    let (service, _) = build_memory_service(&config).await?;
    McpServer::new(service, config.default_scope)?
        .run_stdio()
        .await?;
    Ok(())
}

async fn build_memory_service(
    config: &FleetConfig,
) -> anyhow::Result<(Arc<CockroachMemoryService>, Arc<CockroachStore>)> {
    let embedder: Arc<dyn ChunkEmbedder> = Arc::new(load_pinned_embedder(config)?);
    let store = Arc::new(connect_store(config).await?);
    store.health_check().await?;
    let ledger = Arc::new(CockroachClaimLedger::new(
        store.pool().clone(),
        config.default_scope.clone(),
        embedder.clone(),
        RetryPolicy::default(),
    )?);
    let service = Arc::new(CockroachMemoryService::new(
        config.default_scope.clone(),
        store.clone(),
        ledger,
        embedder,
    )?);
    service.verify_embedding_generation().await?;
    Ok((service, store))
}

