fn load_pinned_embedder(config: &impl PinnedEmbeddingConfig) -> anyhow::Result<PinnedEmbedder> {
    let canonical = config.verified_bundle_path()?;
    let local_path = canonical.to_str().ok_or_else(|| {
        anyhow::anyhow!("embedding model bundle path must be valid UTF-8 for model2vec")
    })?;
    let inner = Embedder::load(local_path).context("load verified local embedding model bundle")?;
    ensure!(
        inner.dim() == EMBEDDING_DIMENSION,
        "embedding model dimension mismatch: schema requires {EMBEDDING_DIMENSION}, bundle produced {}",
        inner.dim()
    );
    Ok(PinnedEmbedder {
        inner,
        identity: config.pinned_model_identity(),
    })
}

fn read_input(input: &str, scope: &FleetScope, model_identity: &str) -> anyhow::Result<Vec<Chunk>> {
    if input == "-" {
        let stdin = io::stdin();
        return read_ndjson(stdin.lock(), scope, model_identity).context("read NDJSON from stdin");
    }

    let path = Path::new(input);
    let file = File::open(path).with_context(|| format!("open NDJSON input {}", path.display()))?;
    ensure!(
        file.metadata()
            .with_context(|| format!("inspect NDJSON input {}", path.display()))?
            .is_file(),
        "NDJSON input {} must be a regular file; use --input - for stdin",
        path.display()
    );
    read_ndjson(BufReader::new(file), scope, model_identity)
        .with_context(|| format!("read NDJSON input {}", path.display()))
}

fn read_ndjson<R: BufRead>(
    mut reader: R,
    scope: &FleetScope,
    model_identity: &str,
) -> anyhow::Result<Vec<Chunk>> {
    let mut chunks = Vec::new();
    let mut chunk_ids = HashSet::new();
    let mut line_number = 0_usize;
    let mut total_bytes = 0_usize;

    loop {
        let mut line = Vec::new();
        let count = (&mut reader)
            .take((MAX_NDJSON_LINE_BYTES + 1) as u64)
            .read_until(b'\n', &mut line)?;
        if count == 0 {
            break;
        }
        line_number += 1;
        ensure!(
            count <= MAX_NDJSON_LINE_BYTES,
            "NDJSON line {line_number} exceeds the {MAX_NDJSON_LINE_BYTES}-byte limit"
        );
        total_bytes = total_bytes
            .checked_add(count)
            .ok_or_else(|| anyhow::anyhow!("NDJSON input size overflow"))?;
        ensure!(
            total_bytes <= MAX_TOTAL_INPUT_BYTES,
            "NDJSON input exceeds the {MAX_TOTAL_INPUT_BYTES}-byte total limit"
        );

        if line.last() == Some(&b'\n') {
            line.pop();
        }
        if line.last() == Some(&b'\r') {
            line.pop();
        }
        if line.iter().all(u8::is_ascii_whitespace) {
            continue;
        }

        ensure!(
            chunks.len() < MAX_INGEST_RECORDS,
            "NDJSON input exceeds the {MAX_INGEST_RECORDS}-record limit"
        );
        let text = std::str::from_utf8(&line)
            .with_context(|| format!("NDJSON line {line_number} is not valid UTF-8"))?;
        let record: IngestRecord = serde_json::from_str(text)
            .with_context(|| format!("invalid NDJSON record at line {line_number}"))?;
        let chunk = build_chunk(record, scope, model_identity)
            .with_context(|| format!("invalid NDJSON record at line {line_number}"))?;
        ensure!(
            chunk_ids.insert(chunk.chunk_id.clone()),
            "duplicate chunk identity at NDJSON line {line_number}"
        );
        chunks.push(chunk);
    }

    ensure!(!chunks.is_empty(), "NDJSON input contains no records");
    Ok(chunks)
}

fn build_chunk(
    mut record: IngestRecord,
    scope: &FleetScope,
    model_identity: &str,
) -> anyhow::Result<Chunk> {
    validate_identifier("source_id", &record.source_id, MAX_SOURCE_ID_BYTES)?;
    validate_identifier(
        "source_config_id",
        &record.source_config_id,
        MAX_SOURCE_CONFIG_ID_BYTES,
    )?;
    ensure!(!record.text.trim().is_empty(), "text must not be blank");
    ensure!(
        record.text.len() <= MAX_TEXT_BYTES,
        "text exceeds the {MAX_TEXT_BYTES}-byte limit"
    );
    ensure!(
        !record.text.contains('\0'),
        "text must not contain NUL bytes"
    );
    validate_tsvector_lexemes(&record.text)?;
    validate_links(&record.links)?;
    validate_facets(&record.facets)?;

    for &reserved in DEPLOYMENT_CONTROLLED_INGEST_KEYS {
        ensure!(
            !record.facets.contains_key(reserved),
            "facet {reserved:?} is deployment-controlled and must be omitted"
        );
    }
    for &reserved in INTERNAL_PROJECTION_INGEST_KEYS {
        ensure!(
            !record.facets.contains_key(reserved),
            "facet {reserved:?} is reserved for Recall internals"
        );
    }
    let extra = record
        .extra
        .as_object()
        .ok_or_else(|| anyhow::anyhow!("extra must be a JSON object"))?;
    for &reserved in DEPLOYMENT_CONTROLLED_INGEST_KEYS
        .iter()
        .chain(INTERNAL_PROJECTION_INGEST_KEYS)
    {
        ensure!(
            !extra.contains_key(reserved),
            "extra field {reserved:?} is reserved for Recall internals"
        );
    }

    record
        .facets
        .insert("project".into(), BTreeSet::from([scope.project.clone()]));
    record
        .facets
        .insert("agent".into(), BTreeSet::from([scope.agent.clone()]));
    validate_facets(&record.facets)?;

    let chunk_id = Chunk::make_id(
        record.source,
        &record.source_id,
        record.chunk_index,
        &record.source_config_id,
    );
    let sha256 = Chunk::content_hash(&record.text);
    let header = compose_header(&filter_to_allowlist(&record.facets));
    let embedding_input_sha256 = Chunk::embedding_input_hash(model_identity, &header, &record.text);
    let chunk = Chunk {
        chunk_id,
        source: record.source,
        project: Some(scope.project.clone()),
        source_id: record.source_id,
        source_config_id: record.source_config_id,
        chunk_index: record.chunk_index,
        ts: record.ts,
        role: record.role.map(|role| role.as_str().to_owned()),
        text: record.text,
        sha256,
        links: record.links,
        facets: record.facets,
        embedding_input_sha256,
        extra: record.extra,
    };
    ensure!(
        !is_archive_parent(&chunk),
        "archive-parent chunks are not accepted by active corpus ingestion"
    );
    Ok(chunk)
}

fn validate_tsvector_lexemes(text: &str) -> anyhow::Result<()> {
    for lexeme in text.split_whitespace() {
        let bytes = lexeme.len();
        ensure!(
            bytes <= MAX_TSVECTOR_INPUT_LEXEME_BYTES,
            "text contains a whitespace-delimited lexeme of {bytes} UTF-8 bytes; \
             the ingest limit is {MAX_TSVECTOR_INPUT_LEXEME_BYTES} bytes to remain below \
             CockroachDB's {COCKROACH_TSVECTOR_LEXEME_BYTES}-byte TSVECTOR lexeme limit"
        );
    }
    Ok(())
}

fn validate_identifier(label: &str, value: &str, max_bytes: usize) -> anyhow::Result<()> {
    ensure!(!value.is_empty(), "{label} must not be empty");
    ensure!(
        value == value.trim(),
        "{label} must not have leading or trailing whitespace"
    );
    ensure!(
        value.len() <= max_bytes,
        "{label} exceeds the {max_bytes}-byte limit"
    );
    ensure!(
        !value.chars().any(char::is_control),
        "{label} must not contain control characters"
    );
    Ok(())
}

fn validate_links(links: &Links) -> anyhow::Result<()> {
    if let Some(value) = &links.duckdb_row_key {
        validate_identifier("links.duckdb_row_key", value, MAX_LINK_ID_BYTES)?;
    }
    if let Some(value) = &links.file_path {
        validate_identifier("links.file_path", value, MAX_LINK_ID_BYTES)?;
    }
    ensure!(
        links.parent_ids.len() <= MAX_PARENT_LINKS,
        "links.parent_ids exceeds the {MAX_PARENT_LINKS}-entry limit"
    );
    for parent_id in &links.parent_ids {
        validate_identifier("links.parent_ids entry", parent_id, MAX_LINK_ID_BYTES)?;
    }
    Ok(())
}

fn validate_facets(facets: &FacetSet) -> anyhow::Result<()> {
    ensure!(
        facets.len() <= MAX_FACET_KEYS,
        "facets exceeds the {MAX_FACET_KEYS}-key limit"
    );
    for (key, values) in facets {
        ensure!(
            key.len() <= MAX_FACET_KEY_BYTES && is_valid_facet_key(key),
            "invalid facet key {key:?}"
        );
        ensure!(!values.is_empty(), "facet {key:?} has no values");
        ensure!(
            values.len() <= MAX_FACET_VALUES_PER_KEY,
            "facet {key:?} exceeds the {MAX_FACET_VALUES_PER_KEY}-value limit"
        );
        for value in values {
            ensure!(!value.is_empty(), "facet {key:?} contains an empty value");
            ensure!(
                value == value.trim(),
                "facet {key:?} values must not have surrounding whitespace"
            );
            ensure!(
                value.len() <= MAX_FACET_VALUE_BYTES,
                "facet {key:?} value exceeds the {MAX_FACET_VALUE_BYTES}-byte limit"
            );
            ensure!(
                !value.chars().any(char::is_control),
                "facet {key:?} values must not contain control characters"
            );
        }
    }
    Ok(())
}

fn embed_chunks(
    chunks: &[Chunk],
    scope: &FleetScope,
    model_identity: &str,
    embedder: &PinnedEmbedder,
) -> anyhow::Result<Vec<ScopedChunk>> {
    let mut rows = Vec::with_capacity(chunks.len());
    for batch in chunks.chunks(EMBED_BATCH_SIZE) {
        let texts = batch
            .iter()
            .map(|chunk| chunk.text.as_str())
            .collect::<Vec<_>>();
        let embeddings = embedder.encode_batch(&texts);
        ensure!(
            embeddings.len() == batch.len(),
            "embedder returned {} vectors for {} chunks",
            embeddings.len(),
            batch.len()
        );
        for (chunk, embedding) in batch.iter().cloned().zip(embeddings) {
            validate_embedding(&embedding)?;
            rows.push(ScopedChunk {
                scope: scope.clone(),
                chunk,
                embedding_model: model_identity.to_owned(),
                embedding,
                stale: false,
            });
        }
    }
    Ok(rows)
}

fn validate_embedding(embedding: &[f32]) -> anyhow::Result<()> {
    ensure!(
        embedding.len() == EMBEDDING_DIMENSION,
        "embedding dimension mismatch: expected {EMBEDDING_DIMENSION}, got {}",
        embedding.len()
    );
    ensure!(
        embedding.iter().all(|component| component.is_finite()),
        "embedding contains a non-finite component"
    );
    let norm_squared = embedding
        .iter()
        .map(|component| f64::from(*component).powi(2))
        .sum::<f64>();
    ensure!(norm_squared > 0.0, "embedding has zero norm");
    Ok(())
}

